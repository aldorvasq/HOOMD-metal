"""Preprocess a HOOMD-blue .metal file and embed it in a C++ source file.

The Metal runtime compiler cannot search include paths, so each .metal translation unit is
expanded at build time with the host C++ preprocessor. The result is checked with the Metal
compiler (hoomd_mslc) and written to a C++ file that defines a hoomd::mtl::KernelSource.
"""

import argparse
import pathlib
import subprocess
import sys

PREAMBLE = "#include <metal_stdlib>\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--compiler", required=True, help="host C++ compiler")
    parser.add_argument("--source", required=True, help=".metal file")
    parser.add_argument("--symbol", required=True, help="name of the KernelSource variable")
    parser.add_argument("--output", required=True, help="C++ file to write")
    parser.add_argument("--msl", required=True, help="preprocessed Metal source to write")
    parser.add_argument("--depfile", required=True, help="Makefile style dependency file")
    parser.add_argument("--validator", help="hoomd_mslc executable to check the source")
    parser.add_argument("-I", dest="includes", action="append", default=[])
    parser.add_argument("-D", dest="defines", action="append", default=[])
    args = parser.parse_args()

    command = [
        args.compiler,
        "-E",
        "-x",
        "c++",
        "-std=c++17",
        "-undef",
        "-nostdinc",
        "-nostdinc++",
        "-D__METAL_VERSION__=320",
        "-DHOOMD_MSL_PREPROCESS",
        "-D__HIPCC__",
        "-D__HIP_DEVICE_COMPILE__",
        "-D__HIP_PLATFORM_METAL__",
        "-MD",
        "-MF",
        args.depfile,
        "-MT",
        args.output,
    ]
    command += [f"-D{d}" for d in args.defines if d]
    command += [f"-I{i}" for i in args.includes if i]
    command.append(args.source)

    result = subprocess.run(command, capture_output=True, text=True)
    if result.returncode != 0:
        sys.stderr.write(result.stderr)
        sys.exit(result.returncode)

    text = PREAMBLE + result.stdout
    msl_path = pathlib.Path(args.msl)
    msl_path.write_text(text)

    if args.validator:
        check = subprocess.run([args.validator, str(msl_path)], capture_output=True, text=True)
        if check.returncode != 0:
            sys.stderr.write(f"Metal compilation of {args.source} failed:\n")
            sys.stderr.write(check.stdout)
            sys.stderr.write(check.stderr)
            sys.exit(1)

    delimiter = "HOOMDMSL"
    if f"){delimiter}" in text:
        sys.stderr.write(f"{args.source}: preprocessed source contains the raw string delimiter\n")
        sys.exit(1)

    # Split the source into chunks to stay well below compiler limits on string literal length.
    chunk = 32768
    pieces = [text[i : i + chunk] for i in range(0, len(text), chunk)]
    literal = "\n".join(f'R"{delimiter}({piece}){delimiter}"' for piece in pieces)

    output = (
        "// Generated by hoomd/mtl/msl_embed.py. Do not edit.\n"
        '#include "hoomd/mtl/MetalRuntime.h"\n\n'
        f"static const char {args.symbol}_text[] =\n{literal};\n\n"
        f"extern const ::hoomd::mtl::KernelSource {args.symbol};\n"
        f"const ::hoomd::mtl::KernelSource {args.symbol}"
        f' = {{"{pathlib.Path(args.source).name}", {args.symbol}_text}};\n'
    )

    pathlib.Path(args.output).write_text(output)


if __name__ == "__main__":
    main()
