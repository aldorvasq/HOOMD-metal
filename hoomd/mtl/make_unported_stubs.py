"""Generate stubs for GPU driver functions that have no Metal implementation yet.

Runs before a module links. Finds GPU driver functions (names containing ``gpu_`` or in a
``kernel`` or ``gpu`` namespace) that the module's object files reference but nothing defines, and
writes a static library with a stub for each. A stub raises a Python RuntimeError (through
hoomd_mtl_unported_kernel) that names the function, so features whose kernels are not yet ported
fail with a clear message instead of preventing the module from linking.
"""

import argparse
import pathlib
import subprocess
import sys


def nm(path, *flags):
    result = subprocess.run(["nm", *flags, path], capture_output=True, text=True)
    if result.returncode != 0:
        return []
    symbols = []
    for line in result.stdout.splitlines():
        parts = line.split()
        if parts:
            symbols.append(parts[-1])
    return symbols


def demangle(symbols):
    if not symbols:
        return []
    # nm reports Mach-O symbols with a leading underscore
    stripped = [s[1:] if s.startswith("_") else s for s in symbols]
    result = subprocess.run(
        ["c++filt"], input="\n".join(stripped), capture_output=True, text=True, check=True
    )
    return result.stdout.splitlines()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--objects", nargs="*", default=[])
    parser.add_argument("--libraries", nargs="*", default=[])
    parser.add_argument("--output", required=True)
    parser.add_argument("--compiler", required=True)
    args = parser.parse_args()

    objects = [o for o in args.objects if o.endswith(".o")]
    defined = set()
    undefined = set()
    for obj in objects:
        defined.update(nm(obj, "-gU", "-j"))
        undefined.update(nm(obj, "-u", "-j"))
    for lib in args.libraries:
        defined.update(nm(lib, "-gU", "-j"))

    missing = sorted(
        s for s in undefined - defined if s.startswith(("__ZN5hoomd", "__ZNK5hoomd"))
    )
    names = demangle(missing)
    stubs = [
        (sym, name)
        for sym, name in zip(missing, names)
        if "gpu_" in name or "::kernel::" in name or "::gpu::" in name
    ]

    out = pathlib.Path(args.output)
    out.parent.mkdir(parents=True, exist_ok=True)
    asm = out.with_suffix(".s")
    obj = out.with_suffix(".o")

    lines = ["// Generated by hoomd/mtl/make_unported_stubs.py", ".section __TEXT,__text"]
    for i, (sym, _) in enumerate(stubs):
        lines += [
            ".p2align 2",
            f".globl {sym}",
            f"{sym}:",
            f"    adrp x0, Lname{i}@PAGE",
            f"    add x0, x0, Lname{i}@PAGEOFF",
            "    b _hoomd_mtl_unported_kernel",
        ]
    lines.append(".section __TEXT,__cstring")
    for i, (_, name) in enumerate(stubs):
        escaped = name.replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'Lname{i}: .asciz "{escaped}"')
    asm.write_text("\n".join(lines) + "\n")

    subprocess.run([args.compiler, "-c", str(asm), "-o", str(obj)], check=True)
    if out.exists():
        out.unlink()
    subprocess.run(["ar", "rcs", str(out), str(obj)], check=True)

    if stubs:
        print(f"Metal: {len(stubs)} GPU driver functions are not yet ported in {out.name}:")
        for _, name in stubs:
            print(f"    {name.split('(')[0]}")
    sys.exit(0)


if __name__ == "__main__":
    main()
